#!/usr/bin/env bun
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
process.chdir(resolve(dir, '..'));
const args = process.argv.slice(2);
if (
    args.some((arg) => !['--check', '--inline'].includes(arg)) ||
    (args.includes('--check') && args.includes('--inline'))
) {
    throw new Error('Usage: bun expo-bridge/build-shell.mjs [--check | --inline]');
}
const built = await Bun.build({
    entrypoints: [resolve(dir, 'shell.ts')],
    target: 'browser',
    format: 'iife',
    minify: false,
    sourcemap: 'none',
});
if (!built.success) throw new AggregateError(built.logs, 'Bridge build failed');
if (built.outputs.length !== 1) throw new Error('Bridge must be a single self-contained script');
const escape = (code) => code.replace(/<\/script/gi, '<\\/script');
const code = await built.outputs[0].text();
let html = (await readFile(resolve(dir, 'shell.template.html'), 'utf8')).replace(
    '/* KALENDUS_BRIDGE */',
    () => escape(code),
);
const inline = args.includes('--inline');
if (inline) {
    const bundle = await readFile(resolve(dir, '../dist/kalendus.iife.js'), 'utf8');
    html = html.replace(
        '<script src="kalendus.iife.js"></script>',
        () => `<script>\n${escape(bundle)}\n</script>`,
    );
}
const output = resolve(dir, inline ? 'kalendus-inline.html' : 'kalendus.html');
if (args.includes('--check')) {
    if ((await readFile(output, 'utf8')) !== html)
        throw new Error('Stale kalendus.html: run bun expo-bridge/build-shell.mjs');
    console.log('Bridge shell is reproducible and current');
} else {
    await writeFile(output, html);
    console.log(`Wrote ${output}`);
    if (inline) {
        const moduleOutput = resolve(dir, 'kalendus-inline.ts');
        await writeFile(
            moduleOutput,
            `// Generated by build-shell.mjs --inline; do not edit.\nexport default ${JSON.stringify(html)};\n`,
        );
        console.log(`Wrote ${moduleOutput}`);
    }
}
